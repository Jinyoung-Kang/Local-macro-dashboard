def _verdict_block(judgements: str) -> str:
    """
    리포트 맨 앞의 '총평' 섹션 서식을 지시하는 문자열을 만듭니다.

    파라미터:
        judgements : 이 리포트 유형에서 허용하는 판단 값들을
                     " | "로 이어 붙인 문자열.

    반환값:
        프롬프트에 끼워 넣을 총평 섹션 지시문.

    반환 형식이 중요한 이유:
        화면이 `- **판단**: 값` 형태를 정규식으로 읽어 배너 색을 고릅니다.
        항목 이름(판단/신뢰도/핵심 근거)과 굵게 표시를 바꾸면 화면이
        총평을 찾지 못해 일반 마크다운으로 떨어집니다.

    주의사항:
        VERDICT_FIELDS와 이 문자열의 항목 이름은 **항상 같아야 합니다.**
        회귀 테스트가 이를 검사합니다.
    """
    return f"""\
### {VERDICT_SECTION}
반드시 아래 네 줄로 시작하십시오. 형식을 그대로 지키십시오.
- **{VERDICT_FIELDS['judgement']}**: {judgements} 중 정확히 하나
- **{VERDICT_FIELDS['confidence']}**: {' | '.join(CONFIDENCE_LEVELS)} 중 정확히 하나
- **{VERDICT_FIELDS['conflicts']}**: 상충 신호의 **개수와 내용**.
  없으면 "없음". 있으면 "2개 — 금리는 위험회피/섹터는 위험선호, ..."처럼
  몇 개인지와 무엇끼리 어긋나는지 쓸 것.
  (이 개수가 위 신뢰도를 결정합니다. 0개가 아니면 '높음'을 쓸 수 없습니다.)
- **{VERDICT_FIELDS['rationale']}**: 한 문장. 가장 결정적인 지표 이름을 포함할 것
"""


def build_report_prompt(
    role: str,
    focus: str,
    judgements: str,
    sections: list[tuple[str, str]],
) -> str:
    """
    리포트 유형 하나의 system prompt를 조립합니다.

    파라미터:
        role       : 모델이 연기할 역할 한 문장.
        focus      : 무엇에 집중하고 무엇을 배경으로 둘지 한두 문장.
        judgements : 총평의 '판단'에 허용되는 값들(" | "로 연결).
        sections   : (섹션 제목, 그 섹션에 쓸 내용 지시) 목록.
                     총평은 자동으로 맨 앞에 붙으므로 넣지 마십시오.

    반환값:
        조립된 system prompt 문자열.

    주의사항:
        - sections의 제목은 화면이 파싱하는 기준입니다. 임의로 바꾸면
          화면의 섹션 분리가 깨집니다(내용은 보존되지만 한 덩어리로
          보입니다).
        - 블록 순서를 바꾸지 마십시오. 데이터 취급 규칙을 뒤쪽에 두면
          모델이 앞의 역할 설명에 휩쓸려 규칙을 덜 지킵니다.
    """
    body = "\n".join(
        f"### {title}\n{instruction.rstrip()}\n" for title, instruction in sections
    )

    return (
        f"{role}\n{focus}\n\n"
        f"{_ANALYST_STANCE}\n"
        f"{_DATA_INTEGRITY}\n"
        f"{_CALIBRATION}\n"
        f"{_STYLE}\n"
        "[출력 구조]\n"
        "아래 섹션을 이 순서대로, 이 제목 그대로 출력하십시오.\n"
        "섹션을 빼거나 추가하거나 제목을 바꾸지 마십시오.\n\n"
        f"{_verdict_block(judgements)}\n"
        f"{body}"
    )


